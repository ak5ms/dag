"""Benchmark persistent, instance-owned CVXPYgen/Clarabel C++ programs.

This measures the production integration generated by
``generate_clarabel_program`` in three steady-state regimes: every input changes,
only expected returns change, and every input is unchanged. Parameter writes use
the same bitwise change check as ``CvxpygenNode``, so unchanged canonical blocks
are not dirtied or recomputed.

The numerical work executes through CVXPYgen's generated parameter maps and
result maps, linked directly to the Clarabel C ABI. No Python solver wrapper is
in the timed section.
"""

