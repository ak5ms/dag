@dataclass(frozen=True)
class Summary:
    repetitions: int
    median_ms: float
    mean_ms: float
    min_ms: float
    max_ms: float


def _summary(values: list[float]) -> Summary:
    return Summary(
        repetitions=len(values),
        median_ms=float(statistics.median(values)),
        mean_ms=float(statistics.mean(values)),
        min_ms=float(min(values)),
        max_ms=float(max(values)),
    )


def _cpu_model() -> str:
    cpuinfo = Path("/proc/cpuinfo")
    if not cpuinfo.is_file():
        return platform.processor() or "unknown"
    for line in cpuinfo.read_text().splitlines():
        if line.startswith("model name"):
            return line.partition(":")[2].strip()
    return platform.processor() or "unknown"


def _compiler_version(cxx: str) -> str:
    completed = subprocess.run(
        [cxx, "--version"], check=True, capture_output=True, text=True
    )
    return completed.stdout.splitlines()[0]


def _problem(n_assets: int, n_horizons: int) -> cp.Problem:
    weights = cp.Variable((n_horizons, n_assets), name="weights")
    turnover = cp.Variable((n_horizons, n_assets), name="turnover")
    expected_returns = cp.Parameter(
        (n_horizons, n_assets), name="expected_returns"
    )
    half_spread = cp.Parameter(
        (n_horizons, n_assets), nonneg=True, name="half_spread"
    )
    current_weights = cp.Parameter(n_assets, name="current_weights")
    risk_radius = cp.Parameter(n_horizons, nonneg=True, name="risk_radius")
    risk_factor = cp.Parameter((n_assets, n_assets), name="risk_factor")
    previous = cp.vstack([current_weights, weights[:-1]])
    delta = weights - previous
    constraints = [turnover >= delta, turnover >= -delta]
    constraints.extend(
        cp.SOC(risk_radius[horizon], risk_factor @ weights[horizon])
        for horizon in range(n_horizons)
    )
    problem = cp.Problem(
        cp.Minimize(
            -cp.sum(cp.multiply(expected_returns, weights))
            + cp.sum(cp.multiply(half_spread, turnover))
        ),
        constraints,
    )
    if not problem.is_dcp(dpp=True):
        raise RuntimeError("MPO benchmark must remain DPP-compliant")
    return problem


_DRIVER = r"""
#include "cpg_instance.hpp"
#include <algorithm>
#include <array>
#include <atomic>
#include <barrier>
#include <bit>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <memory>
#include <pthread.h>
#include <sched.h>
#include <thread>
#include <vector>
#include <time.h>

#ifndef N_ASSETS
#error N_ASSETS must be defined
#endif
#ifndef N_HORIZONS
#error N_HORIZONS must be defined
#endif
#ifndef RUNS
#define RUNS 20
#endif
#ifndef WARMUPS
#define WARMUPS 3
#endif

using Solver = __CLASS_NAME__;
constexpr int N = N_ASSETS;
constexpr int H = N_HORIZONS;
constexpr int ER_SIZE = N * H;
constexpr int FACTOR_SIZE = N * N;

static std::atomic<unsigned long long> allocation_count{0};
static std::atomic<bool> count_allocations{false};

extern "C" void* __real_malloc(std::size_t);
extern "C" void* __real_calloc(std::size_t, std::size_t);
extern "C" void* __real_realloc(void*, std::size_t);
extern "C" void* __real_aligned_alloc(std::size_t, std::size_t);

extern "C" void* __wrap_malloc(std::size_t size) {
    if (count_allocations.load(std::memory_order_relaxed)) {
        allocation_count.fetch_add(1, std::memory_order_relaxed);
    }
    return __real_malloc(size);
}

extern "C" void* __wrap_calloc(std::size_t count, std::size_t size) {
    if (count_allocations.load(std::memory_order_relaxed)) {
        allocation_count.fetch_add(1, std::memory_order_relaxed);
    }
    return __real_calloc(count, size);
}

extern "C" void* __wrap_realloc(void* pointer, std::size_t size) {
    if (count_allocations.load(std::memory_order_relaxed)) {
        allocation_count.fetch_add(1, std::memory_order_relaxed);
    }
    return __real_realloc(pointer, size);
}

extern "C" void* __wrap_aligned_alloc(
    std::size_t alignment, std::size_t size
) {
    if (count_allocations.load(std::memory_order_relaxed)) {
        allocation_count.fetch_add(1, std::memory_order_relaxed);
    }
    return __real_aligned_alloc(alignment, size);
}

enum class Scenario {
    AllChanged,
    ObjectiveOnly,
    Unchanged,
};

static const char* scenario_name(Scenario scenario) {
    switch (scenario) {
        case Scenario::AllChanged: return "all_changed";
        case Scenario::ObjectiveOnly: return "objective_only";
        case Scenario::Unchanged: return "unchanged";
    }
    return "unknown";
}

static double now_s() {
    timespec ts{};
    clock_gettime(CLOCK_MONOTONIC_RAW, &ts);
    return static_cast<double>(ts.tv_sec) + 1e-9 * static_cast<double>(ts.tv_nsec);
}

static long rss_kb() {
    FILE* file = std::fopen("/proc/self/status", "r");
    if (!file) return -1;
    char line[256];
    long value = -1;
    while (std::fgets(line, sizeof(line), file)) {
        if (std::sscanf(line, "VmRSS: %ld kB", &value) == 1) break;
    }
    std::fclose(file);
    return value;
}

static void pin_cpu(int cpu) {
    cpu_set_t set;
    CPU_ZERO(&set);
    CPU_SET(cpu, &set);
    pthread_setaffinity_np(pthread_self(), sizeof(set), &set);
}

struct Inputs {
    std::array<double, ER_SIZE> er{};
    std::array<double, ER_SIZE> hs{};
    std::array<double, N> current{};
    std::array<double, H> radius{};
    std::array<double, FACTOR_SIZE> factor{};
};

static void prepare(Inputs& in, int iteration, int worker, Scenario scenario) {
    if (scenario == Scenario::Unchanged) return;
    const double phase = 0.013 * static_cast<double>(iteration + 1)
                       + 0.071 * static_cast<double>(worker + 1);
    for (int t = 0; t < H; ++t) {
        for (int i = 0; i < N; ++i) {
            const int index = t * N + i;
            in.er[index] = 2e-4 * std::sin(
                0.17 * (i + 1) + 0.31 * (t + 1) + phase);
            if (scenario != Scenario::AllChanged) continue;
            in.hs[index] = 5e-5 + 2e-5 * (
                0.5 + 0.5 * std::cos(0.11 * (i + 1) + phase));
        }
    }
    if (scenario != Scenario::AllChanged) return;
    for (int i = 0; i < N; ++i) {
        in.current[i] = 0.002 * std::sin(0.23 * (i + 1) + phase);
    }
    for (int t = 0; t < H; ++t) {
        in.radius[t] = 0.08 + 0.002 * std::sin(0.19 * (t + 1) + phase);
    }
    const double scale = 1.0 + 0.002 * std::sin(phase);
    for (int column = 0; column < N; ++column) {
        for (int row = 0; row < N; ++row) {
            const double value = row == column
                ? 1.0 + 0.002 * row / static_cast<double>(N > 1 ? N - 1 : 1)
                : 0.003 * std::cos(0.07 * (row + 1) * (column + 1));
            in.factor[row + column * N] = scale * value;
        }
    }
}

template <std::size_t Index, std::size_t Size>
static bool set_if_changed(
    Solver& solver, const std::array<double, Size>& values
) {
    auto target = solver.template parameter_buffer<Index>();
    static_assert(Size == Solver::template parameter_size<Index>());
    bool changed = false;
    for (std::size_t index = 0; index < Size; ++index) {
        changed = std::bit_cast<std::uint64_t>(target[index])
            != std::bit_cast<std::uint64_t>(values[index]);
        if (changed) break;
    }
    if (!changed) return false;
    std::copy(values.begin(), values.end(), target.begin());
    solver.template mark_parameter_dirty<Index>();
    return true;
}

static double solve_one(
    Solver& solver,
    Inputs& inputs,
    bool& has_solution,
    int iteration,
    int worker,
    Scenario scenario
) {
    prepare(inputs, iteration, worker, scenario);
    bool changed = false;
    changed = set_if_changed<0>(solver, inputs.er) || changed;
    changed = set_if_changed<1>(solver, inputs.hs) || changed;
    changed = set_if_changed<2>(solver, inputs.current) || changed;
    changed = set_if_changed<3>(solver, inputs.radius) || changed;
    changed = set_if_changed<4>(solver, inputs.factor) || changed;
    if (changed || !has_solution) {
        solver.solve();
        has_solution = true;
    }
    const auto weights = solver.primal_weights();
    double checksum = 0.0;
    for (int asset = 0; asset < N; ++asset) {
        checksum += weights[asset * H];
    }
    return checksum + 1e-12 * solver.template info<1>();
}

static void serial_result(Scenario scenario) {
    pin_cpu(0);
    Solver solver;
    Inputs inputs;
    bool has_solution = false;
    prepare(inputs, 0, 0, Scenario::AllChanged);
    for (int i = 0; i < WARMUPS; ++i) {
        solve_one(solver, inputs, has_solution, i, 0, scenario);
    }
    const long before = rss_kb();
    std::array<double, RUNS> samples{};
    volatile double checksum = 0.0;
    allocation_count.store(0, std::memory_order_relaxed);
    count_allocations.store(true, std::memory_order_relaxed);
    for (int i = 0; i < RUNS; ++i) {
        const double start = now_s();
        checksum += solve_one(
            solver, inputs, has_solution, WARMUPS + i, 0, scenario);
        samples[i] = (now_s() - start) * 1e3;
    }
    count_allocations.store(false, std::memory_order_relaxed);
    const auto allocations = allocation_count.load(std::memory_order_relaxed);
    const long after = rss_kb();
    auto sorted = samples;
    std::sort(sorted.begin(), sorted.end());
    const double median = RUNS % 2
        ? sorted[RUNS / 2]
        : 0.5 * (sorted[RUNS / 2 - 1] + sorted[RUNS / 2]);
    double mean = 0.0;
    for (double sample : samples) mean += sample;
    mean /= RUNS;
    std::printf(
        "{\"mode\":\"serial\",\"scenario\":\"%s\",\"workers\":1,"
        "\"problems\":%d,"
        "\"mean_ms\":%.9f,\"median_ms\":%.9f,\"min_ms\":%.9f,"
        "\"max_ms\":%.9f,\"rss_delta_kb\":%ld,\"allocations\":%llu,"
        "\"output_bytes_per_problem\":%zu,\"checksum\":%.17g,"
        "\"samples_ms\":[",
        scenario_name(scenario), RUNS, mean, median, sorted.front(), sorted.back(),
        before >= 0 && after >= 0 ? after - before : -1,
        allocations, static_cast<std::size_t>(N) * sizeof(double),
        static_cast<double>(checksum));
    for (int i = 0; i < RUNS; ++i) {
        std::printf("%s%.9f", i == 0 ? "" : ",", samples[i]);
    }
    std::printf("]}\n");
}

static void parallel_result(int workers) {
    workers = std::max(1, workers);
    struct WorkerState {
        Solver solver;
        Inputs inputs;
        bool has_solution{false};
    };
    std::vector<std::unique_ptr<WorkerState>> states;
    for (int worker = 0; worker < workers; ++worker) {
        states.emplace_back(std::make_unique<WorkerState>());
    }
    std::barrier start_barrier(workers + 1);
    std::barrier finish_barrier(workers + 1);
    std::vector<std::thread> threads;
    std::vector<double> checksums(workers, 0.0);
    for (int worker = 0; worker < workers; ++worker) {
        threads.emplace_back([&, worker] {
            pin_cpu(worker);
            auto& state = *states[worker];
            prepare(state.inputs, 0, worker, Scenario::AllChanged);
            for (int i = 0; i < WARMUPS; ++i) {
                checksums[worker] += solve_one(
                    state.solver, state.inputs, state.has_solution, i, worker,
                    Scenario::AllChanged);
            }
            start_barrier.arrive_and_wait();
            for (int i = 0; i < RUNS; ++i) {
                checksums[worker] += solve_one(
                    state.solver, state.inputs, state.has_solution,
                    WARMUPS + i, worker,
                    Scenario::AllChanged);
            }
            finish_barrier.arrive_and_wait();
        });
    }
    start_barrier.arrive_and_wait();
    const double start = now_s();
    finish_barrier.arrive_and_wait();
    const double elapsed = now_s() - start;
    for (auto& thread : threads) thread.join();
    double checksum = 0.0;
    for (double value : checksums) checksum += value;
    const int problems = workers * RUNS;
    std::printf(
        "{\"mode\":\"parallel\",\"workers\":%d,\"problems\":%d,"
        "\"wall_ms\":%.9f,\"ms_per_problem\":%.9f,"
        "\"problems_per_second\":%.9f,\"checksum\":%.17g}\n",
        workers, problems, elapsed * 1e3, elapsed * 1e3 / problems,
        problems / elapsed, checksum);
}

int main(int argc, char** argv) {
    serial_result(Scenario::AllChanged);
    serial_result(Scenario::ObjectiveOnly);
    serial_result(Scenario::Unchanged);
    for (int index = 1; index < argc; ++index) {
        parallel_result(std::atoi(argv[index]));
    }
    return 0;
}
"""


def _compile(
    *,
    artifact: Any,
    n_assets: int,
    n_horizons: int,
    runs: int,
    warmups: int,
    directory: Path,
) -> Path:
    source = directory / "benchmark.cpp"
    binary = directory / "benchmark"
    source.write_text(
        textwrap.dedent(_DRIVER).replace("__CLASS_NAME__", artifact.class_name)
    )
    command = [
        os.environ.get("CXX", "g++"),
        "-std=gnu++20",
        "-O3",
        "-DNDEBUG",
        "-march=native",
        "-mtune=native",
        f"-DN_ASSETS={n_assets}",
        f"-DN_HORIZONS={n_horizons}",
        f"-DRUNS={runs}",
        f"-DWARMUPS={warmups}",
        *(f"-I{path}" for path in artifact.include_dirs),
        str(source),
        str(artifact.clarabel.static_library),
        "-Wl,--wrap=malloc",
        "-Wl,--wrap=calloc",
        "-Wl,--wrap=realloc",
        "-Wl,--wrap=aligned_alloc",
        "-pthread",
        "-ldl",
        "-lm",
        "-o",
        str(binary),
    ]
    subprocess.run(command, check=True)
    # Some overlay filesystems preserve a pre-existing non-executable mode when
    # the linker replaces the file in place.
    binary.chmod(binary.stat().st_mode | 0o111)
    return binary


def _run(binary: Path, workers: list[int]) -> list[dict[str, Any]]:
    completed = subprocess.run(
        [str(binary), *(str(worker) for worker in workers if worker > 1)],
        check=True,
        capture_output=True,
        text=True,
    )
    return [json.loads(line) for line in completed.stdout.splitlines() if line.strip()]


def _markdown(results: dict[str, Any]) -> str:
    lines = [
        "# Persistent CVXPYgen/Clarabel instance benchmark",
        "",
        "Timings cover bitwise parameter change detection, any required bulk copy,",
        "generated CVXPYgen canonicalization, Clarabel update/solve, and the",
        "requested first-horizon weight projection. The timed path is entirely",
        "native C++/C. Allocation counters wrap the process allocator after warmup.",
        "",
        "## Serial hot-path regimes",
        "",
        "| assets × horizons | all changed | objective only | unchanged | allocations | output |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for case in results["cases"]:
        if "error" in case:
            continue
        scenarios = case["scenarios"]
        allocations = max(
            scenario["allocations_max"] for scenario in scenarios.values()
        )
        lines.append(
            f"| {case['assets']} × {case['horizons']} | "
            f"{scenarios['all_changed']['median_ms']:.3f} ms | "
            f"{scenarios['objective_only']['median_ms']:.3f} ms | "
            f"{scenarios['unchanged']['median_ms']:.3f} ms | "
            f"{allocations} | "
            f"{scenarios['all_changed']['output_bytes_per_problem']} B |"
        )
    lines.extend(
        [
            "",
            "## Independent-problem parallel throughput",
            "",
            "`ms/problem` is wall time divided by total problems across workers.",
            "Each worker owns a separate generated CVXPYgen object and persistent",
            "Clarabel solver; immutable generated maps are shared.",
            "",
            "| assets × horizons | workers | ms/problem | problems/s | speedup |",
            "|---:|---:|---:|---:|---:|",
        ]
    )
    for case in results["cases"]:
        if "error" in case:
            continue
        serial_ms = case["serial"]["median_ms"]
        for parallel in case["parallel"]:
            speedup = serial_ms / parallel["median_ms_per_problem"]
            lines.append(
                f"| {case['assets']} × {case['horizons']} | "
                f"{parallel['workers']} | {parallel['median_ms_per_problem']:.3f} ms | "
                f"{parallel['median_problems_per_second']:.1f} | {speedup:.2f}× |"
            )
    lines.extend(
        [
            "",
            "## Compile-time cost",
            "",
            "| assets × horizons | CVXPYgen | C++ compile/link | header | binary |",
            "|---:|---:|---:|---:|---:|",
        ]
    )
    for case in results["cases"]:
        if "error" in case:
            continue
        lines.append(
            f"| {case['assets']} × {case['horizons']} | "
            f"{case['codegen_seconds']:.3f} s | {case['compile_seconds']:.3f} s | "
            f"{case['generated_header_bytes'] / (1024 * 1024):.2f} MB | "
            f"{case['binary_bytes'] / (1024 * 1024):.2f} MB |"
        )
    lines.extend(
        [
            "",
            "## Build and ownership properties",
            "",
            "- CVXPYgen owns DPP validation, parameter maps, canonical cone data,",
            "  and primal/dual result mapping.",
            "- Every generated C++ object owns mutable parameter/canonical/result",
            "  buffers and exactly one persistent Clarabel solver.",
            "- Read-only sparse maps and cone descriptors are `inline static` and",
            "  shared across instances.",
            "- The destructor calls `clarabel_DefaultSolver_free`.",
            "- The warm path is required to report zero wrapped allocator calls.",
            "- No Python or CVXPY work occurs in the measured solve path.",
            "",
        ]
    )
    failed = [case for case in results["cases"] if "error" in case]
    if failed:
        lines.extend(["## Failed cases", ""])
        lines.extend(
            f"- {case['assets']} × {case['horizons']}: `{case['error']}`"
            for case in failed
        )
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", default="9,24,50,75,100,150")
    parser.add_argument("--horizons", type=int, default=8)
    parser.add_argument("--runs", type=int, default=10)
    parser.add_argument("--warmups", type=int, default=1)
    parser.add_argument("--repetitions", type=int, default=3)
    parser.add_argument("--workers", default="2,4,8")
    parser.add_argument("--clarabel-include", type=Path)
    parser.add_argument("--clarabel-library", type=Path)
    parser.add_argument(
        "--reuse-generated",
        action="store_true",
        help="reuse compatible generated sub-program manifests in --work-dir",
    )
    parser.add_argument(
        "--work-dir", type=Path, default=Path(".cvxpygen_persistent_benchmark")
    )
    parser.add_argument(
        "--json-out", type=Path, default=Path("cvxpygen_persistent_instances.json")
    )
    parser.add_argument(
        "--markdown-out",
        type=Path,
        default=Path("cvxpygen_persistent_instances.md"),
    )
    args = parser.parse_args()
    include = args.clarabel_include or os.environ.get("CLARABEL_INCLUDE_DIR")
    library = args.clarabel_library or os.environ.get("CLARABEL_STATIC_LIBRARY")
    if not include or not library:
        raise SystemExit(
            "provide --clarabel-include/--clarabel-library or set "
            "CLARABEL_INCLUDE_DIR/CLARABEL_STATIC_LIBRARY"
        )
    clarabel = ClarabelNativePaths(Path(include), Path(library)).normalized()
    cxx = os.environ.get("CXX", "g++")
    sizes = [int(value) for value in args.sizes.split(",")]
    workers = [int(value) for value in args.workers.split(",")]
    args.work_dir.mkdir(parents=True, exist_ok=True)
    output: dict[str, Any] = {
        "environment": {
            "cpu_count": os.cpu_count(),
            "cpu_affinity": (
                len(os.sched_getaffinity(0))
                if hasattr(os, "sched_getaffinity")
                else None
            ),
            "cpu_model": _cpu_model(),
            "platform": platform.platform(),
            "clarabel_version": clarabel.version,
            "cxx": cxx,
            "cxx_version": _compiler_version(cxx),
        },
        "configuration": {
            "horizons": args.horizons,
            "runs": args.runs,
            "warmups": args.warmups,
            "repetitions": args.repetitions,
            "workers": workers,
        },
        "cases": [],
    }

    def checkpoint() -> None:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(json.dumps(output, indent=2) + "\n")
        args.markdown_out.write_text(_markdown(output))

    for n_assets in sizes:
        case_dir = args.work_dir / f"{n_assets}x{args.horizons}"
        case_dir.mkdir(parents=True, exist_ok=True)
        generated_dir = case_dir / "generated"
        try:
            started = time.perf_counter()
            reused_codegen = bool(
                args.reuse_generated
                and (generated_dir / "cpp" / "cpg_instance_manifest.json").is_file()
            )
            if reused_codegen:
                artifact = load_clarabel_program(
                    generated_dir, clarabel=clarabel
                )
            else:
                artifact = generate_clarabel_program(
                    _problem(n_assets, args.horizons),
                    code_dir=generated_dir,
                    clarabel=clarabel,
                    class_name=f"Mpo{n_assets}x{args.horizons}",
                    prefix=f"mpo_{n_assets}_{args.horizons}_",
                    force=True,
                )
            codegen_seconds = time.perf_counter() - started
            started = time.perf_counter()
            binary = _compile(
                artifact=artifact,
                n_assets=n_assets,
                n_horizons=args.horizons,
                runs=args.runs,
                warmups=args.warmups,
                directory=case_dir,
            )
            compile_seconds = time.perf_counter() - started
            repetitions = [_run(binary, workers) for _ in range(args.repetitions)]
            scenarios = {}
            for scenario_name in ("all_changed", "objective_only", "unchanged"):
                rows = [
                    next(
                        row
                        for row in repetition
                        if row["mode"] == "serial"
                        and row["scenario"] == scenario_name
                    )
                    for repetition in repetitions
                ]
                checksums = {float(row["checksum"]) for row in rows}
                if len(checksums) != 1 or not all(
                    math.isfinite(value) for value in checksums
                ):
                    raise RuntimeError(
                        f"unstable {scenario_name} checksums: {checksums}"
                    )
                scenarios[scenario_name] = {
                    **asdict(_summary([row["median_ms"] for row in rows])),
                    "rss_delta_kb_median": float(
                        statistics.median(row["rss_delta_kb"] for row in rows)
                    ),
                    "allocations_max": max(int(row["allocations"]) for row in rows),
                    "output_bytes_per_problem": int(
                        rows[0]["output_bytes_per_problem"]
                    ),
                    "raw": rows,
                }
            allocation_failures = {
                name: scenario["allocations_max"]
                for name, scenario in scenarios.items()
                if scenario["allocations_max"] != 0
            }
            if allocation_failures:
                raise RuntimeError(
                    f"warm hot path allocated: {allocation_failures}"
                )
            serial = scenarios["all_changed"]
            parallel = []
            for worker in workers:
                rows = [
                    next(
                        row
                        for row in repetition
                        if row["mode"] == "parallel" and row["workers"] == worker
                    )
                    for repetition in repetitions
                ]
                checksums = {float(row["checksum"]) for row in rows}
                if len(checksums) != 1 or not all(
                    math.isfinite(value) for value in checksums
                ):
                    raise RuntimeError(
                        f"unstable {worker}-worker checksums: {checksums}"
                    )
                parallel.append(
                    {
                        "workers": worker,
                        "median_ms_per_problem": float(
                            statistics.median(row["ms_per_problem"] for row in rows)
                        ),
                        "median_problems_per_second": float(
                            statistics.median(
                                row["problems_per_second"] for row in rows
                            )
                        ),
                        "raw": rows,
                    }
                )
            output["cases"].append(
                {
                    "assets": n_assets,
                    "horizons": args.horizons,
                    "codegen_seconds": codegen_seconds,
                    "codegen_reused": reused_codegen,
                    "compile_seconds": compile_seconds,
                    "generated_header_bytes": artifact.instance_header.stat().st_size,
                    "binary_bytes": binary.stat().st_size,
                    "serial": serial,
                    "scenarios": scenarios,
                    "parallel": parallel,
                    "raw": repetitions,
                }
            )
        except Exception as exc:
            output["cases"].append(
                {
                    "assets": n_assets,
                    "horizons": args.horizons,
                    "error": f"{type(exc).__name__}: {exc}",
                }
            )
        checkpoint()
    print(json.dumps(output, indent=2))
    failures = [case for case in output["cases"] if "error" in case]
    if failures:
        raise SystemExit(
            "benchmark failed for "
            + ", ".join(
                f"{case['assets']}x{case['horizons']}" for case in failures
            )
        )


if __name__ == "__main__":
    main()
