"""Benchmark persistent, instance-owned CVXPYgen/Clarabel C++ programs.

This measures the production integration generated by
``generate_clarabel_program``. Every solve changes the dense covariance factor,
expected returns, current weights, half-spreads, and risk radii, so the generated
canonical ``A``, ``q``, and ``b`` blocks are all updated.

The numerical work executes through CVXPYgen's generated parameter maps and
result maps, linked directly to the Clarabel C ABI. No Python solver wrapper is
in the timed section.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import json
import os
from pathlib import Path
import statistics
import subprocess
import textwrap
import time
from typing import Any

import cvxpy as cp

from trading_dsl_engine.cpp_stream.optimizer import (
    ClarabelNativePaths,
    generate_clarabel_program,
)


@dataclass(frozen=True)
class Summary:
    repetitions: int
    median_ms: float
    mean_ms: float
    min_ms: float
    max_ms: float


def _summary(values: list[float]) -> Summary:
    return Summary(
        repetitions=len(values),
        median_ms=float(statistics.median(values)),
        mean_ms=float(statistics.mean(values)),
        min_ms=float(min(values)),
        max_ms=float(max(values)),
    )


def _problem(n_assets: int, n_horizons: int) -> cp.Problem:
    weights = cp.Variable((n_horizons, n_assets), name="weights")
    turnover = cp.Variable((n_horizons, n_assets), name="turnover")
    expected_returns = cp.Parameter(
        (n_horizons, n_assets), name="expected_returns"
    )
    half_spread = cp.Parameter(
        (n_horizons, n_assets), nonneg=True, name="half_spread"
    )
    current_weights = cp.Parameter(n_assets, name="current_weights")
    risk_radius = cp.Parameter(n_horizons, nonneg=True, name="risk_radius")
    risk_factor = cp.Parameter((n_assets, n_assets), name="risk_factor")
    previous = cp.vstack([current_weights, weights[:-1]])
    delta = weights - previous
    constraints = [turnover >= delta, turnover >= -delta]
    constraints.extend(
        cp.SOC(risk_radius[horizon], risk_factor @ weights[horizon])
        for horizon in range(n_horizons)
    )
    problem = cp.Problem(
        cp.Minimize(
            -cp.sum(cp.multiply(expected_returns, weights))
            + cp.sum(cp.multiply(half_spread, turnover))
        ),
        constraints,
    )
    if not problem.is_dcp(dpp=True):
        raise RuntimeError("MPO benchmark must remain DPP-compliant")
    return problem


_DRIVER = r"""
#include "cpg_instance.hpp"
#include <algorithm>
#include <array>
#include <atomic>
#include <barrier>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <memory>
#include <pthread.h>
#include <sched.h>
#include <thread>
#include <vector>
#include <time.h>

#ifndef N_ASSETS
#error N_ASSETS must be defined
#endif
#ifndef N_HORIZONS
#error N_HORIZONS must be defined
#endif
#ifndef RUNS
#define RUNS 20
#endif
#ifndef WARMUPS
#define WARMUPS 3
#endif

using Solver = __CLASS_NAME__;
constexpr int N = N_ASSETS;
constexpr int H = N_HORIZONS;
constexpr int ER_SIZE = N * H;
constexpr int FACTOR_SIZE = N * N;

static double now_s() {
    timespec ts{};
    clock_gettime(CLOCK_MONOTONIC_RAW, &ts);
    return static_cast<double>(ts.tv_sec) + 1e-9 * static_cast<double>(ts.tv_nsec);
}

static long rss_kb() {
    FILE* file = std::fopen("/proc/self/status", "r");
    if (!file) return -1;
    char line[256];
    long value = -1;
    while (std::fgets(line, sizeof(line), file)) {
        if (std::sscanf(line, "VmRSS: %ld kB", &value) == 1) break;
    }
    std::fclose(file);
    return value;
}

static void pin_cpu(int cpu) {
    cpu_set_t set;
    CPU_ZERO(&set);
    CPU_SET(cpu, &set);
    pthread_setaffinity_np(pthread_self(), sizeof(set), &set);
}

struct Inputs {
    std::array<double, ER_SIZE> er{};
    std::array<double, ER_SIZE> hs{};
    std::array<double, N> current{};
    std::array<double, H> radius{};
    std::array<double, FACTOR_SIZE> factor{};
};

static void prepare(Inputs& in, int iteration, int worker) {
    const double phase = 0.013 * static_cast<double>(iteration + 1)
                       + 0.071 * static_cast<double>(worker + 1);
    for (int t = 0; t < H; ++t) {
        for (int i = 0; i < N; ++i) {
            const int index = t * N + i;
            in.er[index] = 2e-4 * std::sin(
                0.17 * (i + 1) + 0.31 * (t + 1) + phase);
            in.hs[index] = 5e-5 + 2e-5 * (
                0.5 + 0.5 * std::cos(0.11 * (i + 1) + phase));
        }
    }
    for (int i = 0; i < N; ++i) {
        in.current[i] = 0.002 * std::sin(0.23 * (i + 1) + phase);
    }
    for (int t = 0; t < H; ++t) {
        in.radius[t] = 0.08 + 0.002 * std::sin(0.19 * (t + 1) + phase);
    }
    const double scale = 1.0 + 0.002 * std::sin(phase);
    for (int column = 0; column < N; ++column) {
        for (int row = 0; row < N; ++row) {
            const double value = row == column
                ? 1.0 + 0.002 * row / static_cast<double>(N > 1 ? N - 1 : 1)
                : 0.003 * std::cos(0.07 * (row + 1) * (column + 1));
            in.factor[row + column * N] = scale * value;
        }
    }
}

static double solve_one(Solver& solver, Inputs& inputs, int iteration, int worker) {
    prepare(inputs, iteration, worker);
    solver.set_expected_returns(inputs.er);
    solver.set_half_spread(inputs.hs);
    solver.set_current_weights(inputs.current);
    solver.set_risk_radius(inputs.radius);
    solver.set_risk_factor(inputs.factor);
    solver.solve();
    return solver.primal_weights()[0]
         + 1e-12 * static_cast<double>(solver.result().info->iter);
}

static void serial_result() {
    pin_cpu(0);
    Solver solver;
    Inputs inputs;
    for (int i = 0; i < WARMUPS; ++i) solve_one(solver, inputs, i, 0);
    const long before = rss_kb();
    std::array<double, RUNS> samples{};
    volatile double checksum = 0.0;
    for (int i = 0; i < RUNS; ++i) {
        const double start = now_s();
        checksum += solve_one(solver, inputs, WARMUPS + i, 0);
        samples[i] = (now_s() - start) * 1e3;
    }
    const long after = rss_kb();
    std::sort(samples.begin(), samples.end());
    const double median = RUNS % 2
        ? samples[RUNS / 2]
        : 0.5 * (samples[RUNS / 2 - 1] + samples[RUNS / 2]);
    double mean = 0.0;
    for (double sample : samples) mean += sample;
    mean /= RUNS;
    std::printf(
        "{\"mode\":\"serial\",\"workers\":1,\"problems\":%d,"
        "\"mean_ms\":%.9f,\"median_ms\":%.9f,\"min_ms\":%.9f,"
        "\"max_ms\":%.9f,\"rss_delta_kb\":%ld,\"checksum\":%.17g}\n",
        RUNS, mean, median, samples.front(), samples.back(),
        before >= 0 && after >= 0 ? after - before : -1,
        static_cast<double>(checksum));
}

static void parallel_result(int workers) {
    workers = std::max(1, workers);
    std::vector<std::unique_ptr<Solver>> solvers;
    std::vector<std::unique_ptr<Inputs>> inputs;
    for (int worker = 0; worker < workers; ++worker) {
        solvers.emplace_back(std::make_unique<Solver>());
        inputs.emplace_back(std::make_unique<Inputs>());
    }
    std::barrier start_barrier(workers + 1);
    std::barrier finish_barrier(workers + 1);
    std::vector<std::thread> threads;
    std::vector<double> checksums(workers, 0.0);
    for (int worker = 0; worker < workers; ++worker) {
        threads.emplace_back([&, worker] {
            pin_cpu(worker);
            for (int i = 0; i < WARMUPS; ++i) {
                checksums[worker] += solve_one(
                    *solvers[worker], *inputs[worker], i, worker);
            }
            start_barrier.arrive_and_wait();
            for (int i = 0; i < RUNS; ++i) {
                checksums[worker] += solve_one(
                    *solvers[worker], *inputs[worker], WARMUPS + i, worker);
            }
            finish_barrier.arrive_and_wait();
        });
    }
    start_barrier.arrive_and_wait();
    const double start = now_s();
    finish_barrier.arrive_and_wait();
    const double elapsed = now_s() - start;
    for (auto& thread : threads) thread.join();
    double checksum = 0.0;
    for (double value : checksums) checksum += value;
    const int problems = workers * RUNS;
    std::printf(
        "{\"mode\":\"parallel\",\"workers\":%d,\"problems\":%d,"
        "\"wall_ms\":%.9f,\"ms_per_problem\":%.9f,"
        "\"problems_per_second\":%.9f,\"checksum\":%.17g}\n",
        workers, problems, elapsed * 1e3, elapsed * 1e3 / problems,
        problems / elapsed, checksum);
}

int main(int argc, char** argv) {
    serial_result();
    for (int index = 1; index < argc; ++index) {
        parallel_result(std::atoi(argv[index]));
    }
    return 0;
}
"""


def _compile(
    *,
    artifact: Any,
    n_assets: int,
    n_horizons: int,
    runs: int,
    warmups: int,
    directory: Path,
) -> Path:
    source = directory / "benchmark.cpp"
    binary = directory / "benchmark"
    source.write_text(
        textwrap.dedent(_DRIVER).replace("__CLASS_NAME__", artifact.class_name)
    )
    command = [
        os.environ.get("CXX", "g++"),
        "-std=gnu++20",
        "-O3",
        "-DNDEBUG",
        "-march=native",
        "-mtune=native",
        f"-DN_ASSETS={n_assets}",
        f"-DN_HORIZONS={n_horizons}",
        f"-DRUNS={runs}",
        f"-DWARMUPS={warmups}",
        *(f"-I{path}" for path in artifact.include_dirs),
        str(source),
        str(artifact.clarabel.static_library),
        "-pthread",
        "-ldl",
        "-lm",
        "-o",
        str(binary),
    ]
    subprocess.run(command, check=True)
    return binary


def _run(binary: Path, workers: list[int]) -> list[dict[str, Any]]:
    completed = subprocess.run(
        [str(binary), *(str(worker) for worker in workers if worker > 1)],
        check=True,
        capture_output=True,
        text=True,
    )
    return [json.loads(line) for line in completed.stdout.splitlines() if line.strip()]


def _markdown(results: dict[str, Any]) -> str:
    lines = [
        "# Persistent CVXPYgen/Clarabel instance benchmark",
        "",
        "Every problem changes the covariance factor and therefore canonical `A`,",
        "as well as `q` and `b`. Timings cover bulk parameter copies, generated",
        "CVXPYgen canonicalization, Clarabel updates/solve, and primal projection.",
        "The timed path is entirely native C++/C.",
        "",
        "## Serial",
        "",
        "| assets × horizons | median | mean | RSS growth |",
        "|---:|---:|---:|---:|",
    ]
    for case in results["cases"]:
        serial = case["serial"]
        lines.append(
            f"| {case['assets']} × {case['horizons']} | "
            f"{serial['median_ms']:.3f} ms | {serial['mean_ms']:.3f} ms | "
            f"{serial['rss_delta_kb_median'] / 1024:.3f} MB |"
        )
    lines.extend(
        [
            "",
            "## Independent-problem parallel throughput",
            "",
            "`ms/problem` is wall time divided by total problems across workers.",
            "Each worker owns a separate generated CVXPYgen object and persistent",
            "Clarabel solver; immutable generated maps are shared.",
            "",
            "| assets × horizons | workers | ms/problem | problems/s | speedup |",
            "|---:|---:|---:|---:|---:|",
        ]
    )
    for case in results["cases"]:
        serial_ms = case["serial"]["median_ms"]
        for parallel in case["parallel"]:
            speedup = serial_ms / parallel["median_ms_per_problem"]
            lines.append(
                f"| {case['assets']} × {case['horizons']} | "
                f"{parallel['workers']} | {parallel['median_ms_per_problem']:.3f} ms | "
                f"{parallel['median_problems_per_second']:.1f} | {speedup:.2f}× |"
            )
    lines.extend(
        [
            "",
            "## Compile-time cost",
            "",
            "| assets × horizons | CVXPYgen | C++ compile/link | header | binary |",
            "|---:|---:|---:|---:|---:|",
        ]
    )
    for case in results["cases"]:
        lines.append(
            f"| {case['assets']} × {case['horizons']} | "
            f"{case['codegen_seconds']:.3f} s | {case['compile_seconds']:.3f} s | "
            f"{case['generated_header_bytes'] / (1024 * 1024):.2f} MB | "
            f"{case['binary_bytes'] / (1024 * 1024):.2f} MB |"
        )
    lines.extend(
        [
            "",
            "## Build and ownership properties",
            "",
            "- CVXPYgen owns DPP validation, parameter maps, canonical cone data,",
            "  and primal/dual result mapping.",
            "- Every generated C++ object owns mutable parameter/canonical/result",
            "  buffers and exactly one persistent Clarabel solver.",
            "- Read-only sparse maps and cone descriptors are `inline static` and",
            "  shared across instances.",
            "- The destructor calls `clarabel_DefaultSolver_free`.",
            "- No Python or CVXPY work occurs in the measured solve path.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", default="9,24,50")
    parser.add_argument("--horizons", type=int, default=8)
    parser.add_argument("--runs", type=int, default=20)
    parser.add_argument("--warmups", type=int, default=3)
    parser.add_argument("--repetitions", type=int, default=3)
    parser.add_argument("--workers", default="2,4")
    parser.add_argument("--clarabel-include", type=Path)
    parser.add_argument("--clarabel-library", type=Path)
    parser.add_argument(
        "--work-dir", type=Path, default=Path(".cvxpygen_persistent_benchmark")
    )
    parser.add_argument(
        "--json-out", type=Path, default=Path("cvxpygen_persistent_instances.json")
    )
    parser.add_argument(
        "--markdown-out",
        type=Path,
        default=Path("cvxpygen_persistent_instances.md"),
    )
    args = parser.parse_args()
    include = args.clarabel_include or os.environ.get("CLARABEL_INCLUDE_DIR")
    library = args.clarabel_library or os.environ.get("CLARABEL_STATIC_LIBRARY")
    if not include or not library:
        raise SystemExit(
            "provide --clarabel-include/--clarabel-library or set "
            "CLARABEL_INCLUDE_DIR/CLARABEL_STATIC_LIBRARY"
        )
    clarabel = ClarabelNativePaths(Path(include), Path(library)).normalized()
    sizes = [int(value) for value in args.sizes.split(",")]
    workers = [int(value) for value in args.workers.split(",")]
    args.work_dir.mkdir(parents=True, exist_ok=True)
    output: dict[str, Any] = {
        "environment": {
            "cpu_count": os.cpu_count(),
            "clarabel_version": clarabel.version,
            "cxx": os.environ.get("CXX", "g++"),
        },
        "configuration": {
            "horizons": args.horizons,
            "runs": args.runs,
            "warmups": args.warmups,
            "repetitions": args.repetitions,
            "workers": workers,
        },
        "cases": [],
    }
    for n_assets in sizes:
        case_dir = args.work_dir / f"{n_assets}x{args.horizons}"
        case_dir.mkdir(parents=True, exist_ok=True)
        generated_dir = case_dir / "generated"
        started = time.perf_counter()
        artifact = generate_clarabel_program(
            _problem(n_assets, args.horizons),
            code_dir=generated_dir,
            clarabel=clarabel,
            class_name=f"Mpo{n_assets}x{args.horizons}",
            prefix=f"mpo_{n_assets}_{args.horizons}_",
            force=True,
        )
        codegen_seconds = time.perf_counter() - started
        started = time.perf_counter()
        binary = _compile(
            artifact=artifact,
            n_assets=n_assets,
            n_horizons=args.horizons,
            runs=args.runs,
            warmups=args.warmups,
            directory=case_dir,
        )
        compile_seconds = time.perf_counter() - started
        repetitions = [_run(binary, workers) for _ in range(args.repetitions)]
        serial_rows = [rows[0] for rows in repetitions]
        serial = {
            **asdict(_summary([row["median_ms"] for row in serial_rows])),
            "rss_delta_kb_median": float(
                statistics.median(row["rss_delta_kb"] for row in serial_rows)
            ),
        }
        parallel = []
        for worker in workers:
            rows = [
                next(
                    row
                    for row in repetition
                    if row["mode"] == "parallel" and row["workers"] == worker
                )
                for repetition in repetitions
            ]
            parallel.append(
                {
                    "workers": worker,
                    "median_ms_per_problem": float(
                        statistics.median(row["ms_per_problem"] for row in rows)
                    ),
                    "median_problems_per_second": float(
                        statistics.median(row["problems_per_second"] for row in rows)
                    ),
                    "raw": rows,
                }
            )
        output["cases"].append(
            {
                "assets": n_assets,
                "horizons": args.horizons,
                "codegen_seconds": codegen_seconds,
                "compile_seconds": compile_seconds,
                "generated_header_bytes": artifact.instance_header.stat().st_size,
                "binary_bytes": binary.stat().st_size,
                "serial": serial,
                "parallel": parallel,
                "raw": repetitions,
            }
        )
    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    args.markdown_out.parent.mkdir(parents=True, exist_ok=True)
    args.json_out.write_text(json.dumps(output, indent=2) + "\n")
    args.markdown_out.write_text(_markdown(output))
    print(json.dumps(output, indent=2))


if __name__ == "__main__":
    main()
